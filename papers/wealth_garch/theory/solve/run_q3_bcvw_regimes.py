"""Writes results_q3_bcvw_regimes.md: a check of the constraint decomposition of
Bayraktar et al. (2026), Section 4.2 and Figure 4(a), that under pi < infinity "the LCR
accounts for most of the value loss".

Their script 00_b2_constraint_decomposition.m (repository at 4a4996ab) sets
pi_cap_common = [], so compute_pi_bar gives the regime "none" an exposure cap of 10 and
"solvency" no ceiling, (1 - 1/y)/a1, which rises towards 1/a1 = 22.2. Their Assumption 3.1,
the condition for a finite value, needs rho > r + (mu - r) pi_inf, that is pi_inf < 5 at
their parameters. "none" (10) and "solvency" (22.2) break it, "lcr" and "both" (1/a3 = 3.33)
do not. The test: solve each regime on [1.02, y_max] for y_max = 2.5 (theirs), 4 and 6 at
their node spacing, by the port of their scheme (bcvw_port.py, their settings) and by
policy iteration with issuance at every state (bcvw_model.py). A value that grows with
y_max is set by where the grid is cut, not by the model.

Also the nesting their text asserts ("the admissible investment sets are nested"): with
no common ceiling the solvency cap exceeds the "none" cap of 10 for y > 1/(1 - 10 a1).

No row of the manuscript rests on these numbers.

    python3 run_q3_bcvw_regimes.py
"""
import hashlib
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np  # noqa: E402
import bcvw_port as bp  # noqa: E402
import bcvw_model as bm  # noqa: E402
import solve_qvi as s  # noqa: E402

REGIMES = ("none", "solvency", "lcr", "both")
YMAX = (2.5, 4.0, 6.0)
DY = (2.5 - 1.02) / 300
PUBLISHED = {"none": 1.4040, "solvency": 1.3872, "lcr": 0.9220, "both": 0.8552}


def cap(y, p):
    """compute_pi_bar.m with a regime, pi_cap empty."""
    y = np.asarray(y, float)
    t1 = (1 / p["a1"]) * (1 - 1 / y)
    t2 = (1 / p["a3"]) * (1 - p["a2"] / y)
    reg = p.get("regime", "both")
    if reg == "none":
        c = np.full_like(y, 10.0 if p.get("pi_cap") is None else p["pi_cap"])
    elif reg == "solvency":
        c = t1
    elif reg == "lcr":
        c = t2
    else:
        c = np.minimum(t1, t2)
    if p.get("pi_cap") is not None:
        c = np.minimum(c, p["pi_cap"])
    return np.where(y <= 1, 0.0, np.maximum(0.0, c))


bp.pi_bar = cap
s.pi_bar = cap


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def job(args):
    reg, ymax = args
    n = int(round((ymax - 1.02) / DY)) + 1
    p = dict(bp.BASE, regime=reg)
    q = bp.solve(p, "QVI", N=n, y_max=ymax)
    v_port = float(np.interp(1.2, q["y"], q["v"]))
    o = bm.solve(dict(bm.BASE, regime=reg), "anywhere", y_max=ymax, n=n)
    return reg, ymax, dict(n=n, v_port=v_port, it_port=q["it"], v_pi=o["v12"], y_star_pi=o["y_star"])


def ceiling_job(args):
    reg, c, ymax = args
    n = int(round((ymax - 1.02) / DY)) + 1
    q = bp.solve(dict(bp.BASE, regime=reg, pi_cap=c), "QVI", N=n, y_max=ymax)
    return reg, c, ymax, float(np.interp(1.2, q["y"], q["v"]))


CEILINGS = (3.0, 4.0, 5.0, 6.0, 8.0)


def main():
    with Pool(6) as pool:
        out = pool.map(job, [(r, y) for r in REGIMES for y in YMAX])
        cj = pool.map(ceiling_job, [(r, c, 2.5) for r in REGIMES for c in CEILINGS]
                      + [(r, c, 4.0) for r in ("none", "solvency") for c in (4.0, 5.0)])
    cm = {(r, c, y): v for r, c, y, v in cj}
    m = {(r, y): o for r, y, o in out}
    p = dict(bp.BASE)
    pins = ", ".join(f"`{f}` sha256 {sha(os.path.join(HERE, f))}"
                     for f in ("bcvw_port.py", "bcvw_model.py", "solve_qvi.py", "run_q3_bcvw_regimes.py"))
    bound = (p["rho"] - p["r"]) / (p["mu"] - p["r"])
    ycross = 1 / (1 - 10 * p["a1"])
    L = ["# Results: the constraint decomposition of Bayraktar et al., Figure 4(a) (generated)", "",
         f"Generated by `run_q3_bcvw_regimes.py`. Pinned: {pins}.", "",
         f"Their parameters, pi_cap empty. Finite value needs pi_inf < (rho - r)/(mu - r) = {bound:.2f}. "
         f"pi_inf: none 10, solvency 1/a1 = {1 / p['a1']:.1f}, lcr and both 1/a3 = {1 / p['a3']:.2f}. "
         f"Node spacing {DY:.5f}, theirs, on every grid. v(1.2) by the port (their scheme and settings) and by "
         "policy iteration (issuance at every state).", "",
         "| regime | published | " + " | ".join(f"port, y_max {y}" for y in YMAX) + " | "
         + " | ".join(f"policy iteration, y_max {y}" for y in YMAX) + " | barrier by policy iteration, y_max 2.5, 4, 6 |",
         "|---|---|" + "---|" * (2 * len(YMAX) + 1)]
    for r in REGIMES:
        L.append(f"| {r} | {PUBLISHED[r]:.4f} | " + " | ".join(f"{m[(r, y)]['v_port']:.4f}" for y in YMAX) + " | "
                 + " | ".join(f"{m[(r, y)]['v_pi']:.4f}" for y in YMAX) + " | "
                 + ", ".join(f"{m[(r, y)]['y_star_pi']:.3f}" for y in YMAX) + " |")
    L += ["", "Value loss against \"none\", by policy iteration:", "",
          "| y_max | solvency | lcr | both | share of the loss of both that lcr alone gives |", "|---|---|---|---|---|"]
    for y in YMAX:
        vn = m[("none", y)]["v_pi"]
        ls = {r: vn - m[(r, y)]["v_pi"] for r in REGIMES}
        L.append(f"| {y} | {ls['solvency']:.4f} | {ls['lcr']:.4f} | {ls['both']:.4f} | {ls['lcr'] / ls['both']:.2f} |")
    yy = np.linspace(1.02, 2.5, 2001)
    over = yy[cap(yy, dict(p, regime="solvency")) > 10.0]
    L += ["", f"Nesting: with no common ceiling the solvency cap exceeds the \"none\" cap of 10 for y > "
          f"1/(1 - 10 a1) = {ycross:.4f}" + (f", on [{over.min():.3f}, 2.5] of their grid." if len(over) else "."), ""]
    L += ["## A common ceiling", "",
          "Their text says the regime \"none\" imposes \"a common exogenous leverage ceiling\" and that the sets are "
          "nested. The port at their settings with a common ceiling pi <= c on every regime, y_max = 2.5, and for c = 4 "
          "and 5 also y_max = 4.", "",
          "| c | none | solvency | lcr | both | share of the loss of both that lcr alone gives | none at y_max 4 | solvency at y_max 4 |",
          "|---|---|---|---|---|---|---|---|"]
    for c in CEILINGS:
        vals = {r: cm[(r, c, 2.5)] for r in REGIMES}
        share = (vals["none"] - vals["lcr"]) / (vals["none"] - vals["both"]) if vals["none"] > vals["both"] else float("nan")
        extra = (f"{cm[('none', c, 4.0)]:.4f} | {cm[('solvency', c, 4.0)]:.4f}" if ("none", c, 4.0) in cm else " | ")
        L.append(f"| {c} | {vals['none']:.4f} | {vals['solvency']:.4f} | {vals['lcr']:.4f} | {vals['both']:.4f} | "
                 f"{share:.2f} | {extra} |")
    L += ["", f"Published: none 1.4040, solvency 1.3872, lcr 0.9220, both 0.8552, share "
          f"{(1.4040 - 0.9220) / (1.4040 - 0.8552):.2f}. The finite-value bound on the ceiling is {bound:.2f}.", ""]
    open(os.path.join(HERE, "results_q3_bcvw_regimes.md"), "w").write("\n".join(L))
    print("written results_q3_bcvw_regimes.md")


if __name__ == "__main__":
    main()
