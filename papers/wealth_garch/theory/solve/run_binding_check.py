"""Writes results_binding.md: the condition of M16 for the cap to be the optimal exposure,
checked against the solver at the two baselines of the paper (Bayraktar et al. with
r = 0.02, Section 3; the illustration of Appendix B with r = 0.025), at (lambda_S, K) =
(1.2, 0.05), on 1201 nodes.

In units of exposure U = pi x the first term of the equation is
h(U) = (A/2)(U^2 S - 2 U D) + B m U, with A = V'', B = V', S = sigma^2,
D = c sigma sigma_L (x - 1), m = mu_s - r. By M16 the cap U = u(x) is optimal where
A >= 0 (given u(x) S >= 2 D) and, where A < 0, exactly when G = A (u S - D) + B m >= 0.
The script reports, on the inaction region [x_L, y*], the share of nodes where A >= 0,
the smallest G / (B m) where A < 0, the nodes the condition predicts below the cap, and
the agreement with the solver's exposure. Outside the inaction region V is affine, so
A = 0 and the condition holds. No row rests on these numbers.

    python3 run_binding_check.py
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np  # noqa: E402
import solve_qvi as s  # noqa: E402

CASES = [("Section 3, Bayraktar et al. with r = 0.02", dict(s.BASE, r=0.02, kappa=0.01, lam=1.2, K=0.05)),
         ("Appendix B illustration, r = 0.025", dict(s.BASE, lam=1.2, K=0.05))]


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def check(p):
    x, v, it, resid = s.solve_howard(p, dict(s.GRID, n=1201))
    th = s.thresholds(x, v, p)
    q = th["q"]
    iL, ist = q["iL"], q["istar"]
    A, B = q["v2"], q["v1"]
    U = s.pi_bar(x, p) * x
    S = p["sigma"] ** 2
    D = p["c"] * p["sigma"] * p["sigma_L"] * (x - 1)
    m = p["mu"] - p["r"]
    G = A * (U * S - D) + B * m
    sl = slice(iL + 1, ist)        # interior nodes, where the finite differences are centred
    pred_bind = (A[sl] >= 0) | (G[sl] >= 0)
    at_cap = np.isclose(q["pi"][sl], s.pi_bar(x[sl], p), rtol=1e-9)
    concave = A[sl] < 0
    ratio = (G[sl] / (B[sl] * m))[concave] if concave.any() else np.array([np.nan])
    below = x[sl][~pred_bind]
    xbar = 1 + p["a1"] * (1 - p["a2"]) / (p["a3"] - p["a1"])
    cond = 2 * max(p["a1"], p["a3"]) * p["c"] * p["sigma_L"]
    return dict(x_L=th["x_L"], y_star=th["y_star"], xbar=xbar, n=int(sl.stop - sl.start),
                share_convex=float(np.mean(A[sl] >= 0)), min_ratio=float(np.nanmin(ratio)),
                below=(float(below.min()), float(below.max())) if len(below) else None,
                n_below=int(len(below)), agree=float(np.mean(pred_bind == at_cap)),
                A_xL=float(A[iL + 1]), A_ystar=float(A[ist]), cond=cond, sigma=p["sigma"], resid=resid)


def main():
    pins = ", ".join(f"`{f}` sha256 {sha(os.path.join(HERE, f))}" for f in ("solve_qvi.py", "run_binding_check.py"))
    L = ["# Results: when the optimal exposure binds the cap (generated)", "",
         f"Generated by `run_binding_check.py`. Pinned: {pins}.", "",
         "(lambda_S, K) = (1.2, 0.05), 1201 nodes. G = A (u S - D) + B m with A = V'', B = V' by central "
         "differences on the interior nodes of the inaction region.", "",
         "| baseline | x_L | y* | crossing point | sigma against 2 max(a1, a3) c sigma_L | V'' just above x_L | "
         "V'' at y* | share of nodes with V'' >= 0 | smallest G/(V' m) where V'' < 0 | nodes predicted below the cap | "
         "agreement with the solver |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, p in CASES:
        o = check(p)
        below = "none" if o["below"] is None else f"{o['n_below']}, on [{o['below'][0]:.3f}, {o['below'][1]:.3f}]"
        L.append(f"| {name} | {o['x_L']:.4f} | {o['y_star']:.4f} | {o['xbar']:.4f} | {o['sigma']} against {o['cond']:.4f} | "
                 f"{o['A_xL']:.3f} | {o['A_ystar']:.4f} | {o['share_convex']:.2f} | {o['min_ratio']:.3f} | {below} | "
                 f"{o['agree']:.4f} |")
    L.append("")
    open(os.path.join(HERE, "results_binding.md"), "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
