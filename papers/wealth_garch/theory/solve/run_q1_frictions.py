"""Writes results_q1.md: Question 1 of the comparative statics, pass 1.

How the dividend barrier y*, the recapitalisation trigger x_L, the injection target
y_post and the value function at x = 1.2 move with each friction, one at a time around
(lambda_S, K, kappa) = (1.2, 0.05, 0.01), at the parameters of Bayraktar et al. (2026)
with r = 0.02, with the regulatory cap of A2 alone (leveraged) and with pi <= 1 (no
borrowing, their main banking case). The signs are set against M1 and M2: y* rises
with lambda_S and with K, x_L rises with lambda_S and falls with K. Regimes as in
run_illustration.py (interior trigger or trigger at the distress boundary).

No row of the manuscript rests on these numbers.

    python3 run_q1_frictions.py
"""
import hashlib
import json
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np  # noqa: E402
import solve_qvi as s  # noqa: E402

CENTRE = dict(lam=1.2, K=0.05, kappa=0.01)
SWEEPS = {"lam": [1.0, 1.05, 1.1, 1.2, 1.35, 1.5, 2.0],
          "K": [0.005, 0.01, 0.02, 0.035, 0.05, 0.075, 0.1, 0.15],
          "kappa": [0.0, 0.005, 0.01, 0.02, 0.05, 0.1]}
EXPECTED = {("lam", "y_star"): "rises", ("lam", "x_L"): "rises", ("K", "y_star"): "rises", ("K", "x_L"): "falls"}
N = 601
_unc = s.pi_bar


def capped(x, p):
    return np.minimum(_unc(x, p), 1.0)


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def row(args):
    case, par, val = args
    s.pi_bar = capped if case == "pi <= 1" else _unc
    p = dict(s.BASE, r=0.02, **CENTRE)
    p[par] = val
    x, v, it, resid = s.solve_howard(p, dict(s.GRID, n=N))
    th = s.thresholds(x, v, p)
    q = th["q"]
    dx = x[1] - x[0]
    kind = "distress boundary" if q["iL"] <= 1 else "interior"
    return case, par, val, dict(y_star=th["y_star"], x_L=th["x_L"], y_post=th["y_post"],
                                v12=float(np.interp(1.2, x, v)), kind=kind, resid=resid,
                                size=th["y_post"] - th["x_L"])


def direction(seq):
    d = np.sign(np.round(np.diff(seq), 6))
    if np.all(d > 0):
        return "rises"
    if np.all(d < 0):
        return "falls"
    if np.all(d >= 0):
        return "rises weakly"
    if np.all(d <= 0):
        return "falls weakly"
    return "not monotone"


def main():
    jobs = [(case, par, val) for case in ("A2 alone", "pi <= 1") for par in SWEEPS for val in SWEEPS[par]]
    with Pool(8) as pool:
        out = pool.map(row, jobs)
    m = {(c, a, b): o for c, a, b, o in out}
    pins = ", ".join(f"`{f}` sha256 {sha(os.path.join(HERE, f))}" for f in ("solve_qvi.py", "run_q1_frictions.py"))
    L = ["# Results: Question 1, the thresholds against each friction (generated)", "",
         f"Generated by `run_q1_frictions.py`. Pinned: {pins}.", "",
         f"Parameters of Bayraktar et al. (2026) with r = 0.02, R = 1.15, {N} nodes on [1, 2.5]. Centre "
         f"(lambda_S, K, kappa) = (1.2, 0.05, 0.01); one friction moves at a time. Issue size is y_post - x_L.", ""]
    for case in ("A2 alone", "pi <= 1"):
        L += [f"## Cap: {case}", ""]
        for par in SWEEPS:
            L += [f"### {par}", "", "| value | y* | x_L | y_post | issue size | v(1.2) | trigger | QVI residual |",
                  "|---|---|---|---|---|---|---|---|"]
            for val in SWEEPS[par]:
                o = m[(case, par, val)]
                L.append(f"| {val} | {o['y_star']:.4f} | {o['x_L']:.4f} | {o['y_post']:.4f} | {o['size']:.4f} | "
                         f"{o['v12']:.4f} | {o['kind']} | {o['resid']:.1e} |")
            L.append("")
        L += ["### Directions, over the points with an interior trigger", "",
              "| friction | y* | x_L | y_post | issue size | v(1.2) | M1, M2 expect y* | M1, M2 expect x_L | points interior |",
              "|---|---|---|---|---|---|---|---|---|"]
        for par in SWEEPS:
            os_ = [m[(case, par, v)] for v in SWEEPS[par] if m[(case, par, v)]["kind"] == "interior"]
            dirs = [direction([o[k] for o in os_]) if len(os_) > 1 else "n/a" for k in ("y_star", "x_L", "y_post", "size", "v12")]
            L.append(f"| {par} | " + " | ".join(dirs) + f" | {EXPECTED.get((par, 'y_star'), 'no row')} | "
                     f"{EXPECTED.get((par, 'x_L'), 'no row')} | {len(os_)} of {len(SWEEPS[par])} |")
        L.append("")
    open(os.path.join(HERE, "results_q1.md"), "w").write("\n".join(L))
    json.dump([(c, a, b, o) for c, a, b, o in out], open(os.path.join(HERE, "results_q1.json"), "w"), indent=1, default=float)
    print("written results_q1.md")


if __name__ == "__main__":
    main()
