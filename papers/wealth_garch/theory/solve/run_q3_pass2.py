"""Writes results_q3_pass2.md: Question 3, pass 2.

1. The determinant of M3 along the sweeps of the solvency floor a1 and the liquidity
   haircut a3, at (lambda_S, K) = (1.2, 0.05) and the parameters of Bayraktar et al.
   (2026), by the formula of M3 and by finite differences (re-solving at lambda_S +- 0.02
   and K +- 0.005), with every hypothesis of M1, M2 and M4 checked at each point.
   Tests whether identification weakens as the solvency floor rises, as the spreads of
   results_q3.md section 4 suggest.
2. The bridge in the fixed issuance cost. lambda_S = 1 and K falling to 0.001 in the
   paper's model, against Bayraktar et al.'s model converged by policy iteration.

No row of the manuscript rests on these numbers.

    python3 run_q3_pass2.py
"""
import hashlib
import json
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np  # noqa: E402
import bcvw_model as bm  # noqa: E402
import solve_qvi as s  # noqa: E402

A1 = [0.045, 0.05, 0.06, 0.07, 0.08, 0.09, 0.10, 0.11, 0.12]
A3 = [0.24, 0.27, 0.30, 0.33, 0.36, 0.39, 0.42, 0.45, 0.48]
KS = [0.05, 0.02, 0.01, 0.005, 0.002, 0.001]
N = 601


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def det_row(args):
    par, val = args
    p = dict(s.BASE, r=0.02, kappa=0.01, lam=1.2, K=0.05, **{par: val})
    o = s.check_point(p, N, 0.02, 0.005)
    return par, val, dict(y_star=o["y_star"], x_L=o["x_L"], y_post=o["y_post"],
                          formula=o["formula"], numeric=o["numeric"],
                          det_formula=o["det_formula"], det_numeric=o["det_numeric"],
                          cap_share=o["cap_share_inaction"],
                          failed=[k for k, v in o["hypotheses"].items() if not v])


def bridge_row(K):
    p = dict(s.BASE, r=0.02, kappa=0.01, lam=1.0, K=K)
    x, v, it, resid = s.solve_howard(p, dict(s.GRID, n=N))
    th = s.thresholds(x, v, p)
    return K, dict(y_star=th["y_star"], x_L=th["x_L"], y_post=th["y_post"], v12=float(np.interp(1.2, x, v)), resid=resid)


def main():
    pins = ", ".join(f"`{f}` sha256 {sha(os.path.join(HERE, f))}"
                     for f in ("solve_qvi.py", "bcvw_model.py", "run_q3_pass2.py"))
    with Pool(8) as pool:
        dets = pool.map(det_row, [("a1", v) for v in A1] + [("a3", v) for v in A3])
        print("determinants done", flush=True)
        bridge = pool.map(bridge_row, KS)
        print("bridge done", flush=True)
    b = bm.solve(bm.BASE, "anywhere", n=N)

    L = ["# Results: Question 3, pass 2 (generated)", "",
         f"Generated by `run_q3_pass2.py`. Pinned: {pins}.", "",
         "Parameters of Bayraktar et al. (2026) with r = 0.02, kappa = 0.01, R = 1.15, the paper's model on [1, 2.5], "
         f"{N} nodes.", "",
         "## 1. The determinant of M3 along the cap geometry, (lambda_S, K) = (1.2, 0.05)", "",
         "J = (dy*/dlambda_S)(dx_L/dK) - (dy*/dK)(dx_L/dlambda_S). Formula from M1 and M2; finite differences from "
         "re-solving at lambda_S +- 0.02 and K +- 0.005. Hypotheses are those of M1, M2 and M4.", "",
         "| parameter | value | y* | x_L | dy*/dlam (formula, FD) | dx_L/dlam (formula, FD) | dy*/dK (formula, FD) | "
         "dx_L/dK (formula, FD) | J formula | J FD | share of inaction at the cap | hypotheses failing |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for par, val, o in dets:
        f, n = o["formula"], o["numeric"]
        L.append(f"| {par} | {val} | {o['y_star']:.4f} | {o['x_L']:.4f} | "
                 f"{f['dystar_dlam']:.4f}, {n['dystar_dlam']:.4f} | {f['dxL_dlam']:.4f}, {n['dxL_dlam']:.4f} | "
                 f"{f['dystar_dK']:.3f}, {n['dystar_dK']:.3f} | {f['dxL_dK']:.3f}, {n['dxL_dK']:.3f} | "
                 f"{o['det_formula']:.4f} | {o['det_numeric']:.4f} | {o['cap_share']:.2f} | "
                 f"{', '.join(o['failed']) if o['failed'] else 'none'} |")
    L += ["", "## 2. The bridge in the fixed issuance cost, lambda_S = 1", "",
          "The paper's model with K falling towards zero, against Bayraktar et al.'s model converged by policy "
          "iteration with issuance at every state (`bcvw_model.py`). The models still differ in the lower end of the "
          "state (1 against 1.02), in liquidation (none against y - 1 at any state) and in the form of the issuance cost.", "",
          "| K | y* | x_L | y_post | v(1.2) | QVI residual |", "|---|---|---|---|---|---|"]
    for K, o in bridge:
        L.append(f"| {K} | {o['y_star']:.4f} | {o['x_L']:.4f} | {o['y_post']:.4f} | {o['v12']:.4f} | {o['resid']:.1e} |")
    L += [f"| Bayraktar et al., converged | {b['y_star']:.4f} | {b['issue_top']:.4f} | {b['target']:.4f} | {b['v12']:.4f} | |", ""]
    open(os.path.join(HERE, "results_q3_pass2.md"), "w").write("\n".join(L))
    json.dump(dict(determinants=dets, bridge=bridge), open(os.path.join(HERE, "results_q3_pass2.json"), "w"),
              indent=1, default=float)
    print("written results_q3_pass2.md")


if __name__ == "__main__":
    main()
