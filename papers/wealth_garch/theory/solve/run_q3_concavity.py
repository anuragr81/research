"""Writes results_q3_concavity.md: the numbers behind BCVW-D10 and the sentence of
Appendix B that the value function of Bayraktar et al. (2026) is not concave at their
baseline. Their model solved by policy iteration (bcvw_model.py) on 601, 1201 and 2401
nodes, with issuance allowed at every state and only at the distress threshold 1.02.

For each grid: the slope of v on the first interval above 1.02, the largest slope below
1.35 and where it is, the rise between them (a rise means v is not concave), the region
where the bank issues, and the region below 1.3 where it pays a dividend (with issuance
only at 1.02, a dividend there moves the state to 1.02, where the bank issues at once).

No row of the manuscript rests on these numbers.

    python3 run_q3_concavity.py
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np  # noqa: E402
import bcvw_model as bm  # noqa: E402


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def main():
    pins = ", ".join(f"`{f}` sha256 {sha(os.path.join(HERE, f))}"
                     for f in ("bcvw_model.py", "solve_qvi.py", "run_q3_concavity.py"))
    L = ["# Results: concavity of the value function of Bayraktar et al. at their baseline (generated)", "",
         f"Generated by `run_q3_concavity.py`. Pinned: {pins}.", "",
         "Their baseline parameters (`bcvw_model.BASE`). Marginal cost of issuance 1/(1-kappa') = "
         f"{1 / (1 - bm.BASE['kappa_p']):.4f}.", "",
         "| issuance | nodes | slope just above 1.02 | largest slope below 1.35 | at y | rise | bank issues on | "
         "bank pays a dividend below 1.3 on | v(1.2) |", "|---|---|---|---|---|---|---|---|---|"]
    for mode in ("boundary", "anywhere"):
        for n in (601, 1201, 2401):
            o = bm.solve(bm.BASE, mode, n=n)
            x, v, a = o["x"], o["v"], o["act"]
            dx = x[1] - x[0]
            sl = np.diff(v) / dx
            xm = 0.5 * (x[1:] + x[:-1])
            k = np.searchsorted(xm, 1.35)
            imax = int(np.argmax(sl[:k]))
            iss = x[a == 1]
            low = x[(a == 2) & (x < 1.3)]
            L.append(f"| {'only at 1.02' if mode == 'boundary' else 'at every state'} | {n} | {sl[0]:.4f} | "
                     f"{sl[imax]:.4f} | {xm[imax]:.4f} | {sl[imax] - sl[0]:.4f} | "
                     f"[{iss.min():.4f}, {iss.max():.4f}] | "
                     + (f"[{low.min():.4f}, {low.max():.4f}]" if len(low) else "none") + f" | {o['v12']:.5f} |")
            print(mode, n, "done", flush=True)
    open(os.path.join(HERE, "results_q3_concavity.md"), "w").write("\n".join(L) + "\n")
    print("written results_q3_concavity.md")


if __name__ == "__main__":
    main()
