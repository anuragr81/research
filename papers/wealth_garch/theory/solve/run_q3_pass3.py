"""Writes results_q3_pass3.md: Question 3, pass 3. The determinant of M3 along the
solvency floor a1 and the liquidity haircut a3 on finer grids, to test by finite
differences what pass 2 found by the formula of M3, that the determinant shrinks as
the solvency floor rises.

Pass 2 used 601 nodes and steps of 0.02 in lambda_S, so the finite-difference
response of the dividend barrier to lambda_S moved in steps of dx/(2h) = 0.0625. Here
1201 nodes with h = 0.1 (steps of 0.0063) and 2401 nodes with h = 0.2 (steps of
0.0016), both with h = 0.01 in K. Parameters of Bayraktar et al. (2026) with r = 0.02,
kappa = 0.01, at (lambda_S, K) = (1.2, 0.05).

No row of the manuscript rests on these numbers.

    python3 run_q3_pass3.py
"""
import hashlib
import json
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np  # noqa: E402
import solve_qvi as s  # noqa: E402

A1 = [0.045, 0.05, 0.06, 0.07, 0.08, 0.09, 0.10, 0.11, 0.12]
A3 = [0.27, 0.33, 0.36, 0.39, 0.42, 0.45, 0.48, 0.24]
GRIDS = [(1201, 0.1, 0.01), (2401, 0.2, 0.01)]


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def det_row(args):
    n, hl, hk, par, val = args
    p = dict(s.BASE, r=0.02, kappa=0.01, lam=1.2, K=0.05, **{par: val})
    o = s.check_point(p, n, hl, hk)
    return n, par, val, dict(formula=o["formula"], numeric=o["numeric"], det_formula=o["det_formula"],
                             det_numeric=o["det_numeric"], W=o["W_y_star"], N=o["N_y_star"],
                             failed=[k for k, v in o["hypotheses"].items() if not v])


def main():
    jobs = [(n, hl, hk, par, v) for n, hl, hk in GRIDS for par, vals in (("a1", A1), ("a3", A3)) for v in vals]
    jobs.sort(key=lambda j: -j[0])
    with Pool(6) as pool:
        out = pool.map(det_row, jobs)
    m = {(n, par, val): o for n, par, val, o in out}
    pins = ", ".join(f"`{f}` sha256 {sha(os.path.join(HERE, f))}" for f in ("solve_qvi.py", "run_q3_pass3.py"))
    L = ["# Results: Question 3, pass 3, the determinant on finer grids (generated)", "",
         f"Generated by `run_q3_pass3.py`. Pinned: {pins}.", "",
         "J = (dy*/dlambda_S)(dx_L/dK) - (dy*/dK)(dx_L/dlambda_S) at (lambda_S, K) = (1.2, 0.05), by the formula of "
         "M3 evaluated on the solve and by central finite differences. W(y*) is the expected discounted shortfall "
         "at the barrier, the numerator of dy*/dlambda_S in M1.", ""]
    for n, hl, hk in GRIDS:
        L += [f"## {n} nodes, h = {hl} in lambda_S, h = {hk} in K", "",
              "| parameter | value | dy*/dlam formula | dy*/dlam FD | dx_L/dlam formula | dx_L/dlam FD | dy*/dK formula | "
              "dy*/dK FD | dx_L/dK formula | dx_L/dK FD | J formula | J FD | W(y*) | hypotheses failing |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for par, vals in (("a1", A1), ("a3", sorted(A3 + [0.30]))):
            for v in vals:
                o = m.get((n, par, v)) or m.get((n, "a1", 0.045))
                f, d = o["formula"], o["numeric"]
                L.append(f"| {par} | {v} | {f['dystar_dlam']:.4f} | {d['dystar_dlam']:.4f} | {f['dxL_dlam']:.4f} | "
                         f"{d['dxL_dlam']:.4f} | {f['dystar_dK']:.3f} | {d['dystar_dK']:.3f} | {f['dxL_dK']:.3f} | "
                         f"{d['dxL_dK']:.3f} | {o['det_formula']:.4f} | {o['det_numeric']:.4f} | {o['W']:.4f} | "
                         f"{', '.join(o['failed']) if o['failed'] else 'none'} |")
        L.append("")
    open(os.path.join(HERE, "results_q3_pass3.md"), "w").write("\n".join(L))
    json.dump([(n, par, val, o) for n, par, val, o in out], open(os.path.join(HERE, "results_q3_pass3.json"), "w"),
              indent=1, default=float)
    print("written results_q3_pass3.md")


if __name__ == "__main__":
    main()
