"""Writes results_noborrow.md: the solve of the theory paper's model with no borrowing, pi <= 1.

The solve of run_illustration.py takes the cap of A2 alone, under which the
exposure is pi = 3.2 to 3.3 over most of the inaction region (borrowing to
hold the risky asset), the leveraged case that C3 calls the mathematical
benchmark. C3 says that with no borrowing the liquidity branch never binds, so
the cap is min{(x-1)/a_1, x}. This script imposes pi <= 1 on the same model
and the same scheme (solve_qvi.py is not edited; its cap function is
replaced here) and asks of it what the manuscript asks of the leveraged case.

1. At (lambda_S, K) = (1.2, 0.05), on 601 and 1201 nodes, every hypothesis of
   M1, M2 and M4, the envelope identities and the responses of the thresholds,
   as in run_illustration.py.
2. Buffer variance zeta(x) = sigma^2(x, pi(x))/(x-1)^2 along the inaction
   region [x_L, y*] under the optimal exposure, against the deficit limit
   nu_1^2, the surplus limit nu_3^2 and the bound of M12, for the leveraged
   cap and for pi <= 1.
3. The trigger regimes over the 56 values of (lambda_S, K), on 401 nodes.

No row of the manuscript rests on these numbers.

    python3 run_noborrow.py
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np  # noqa: E402
import solve_qvi as s  # noqa: E402
import run_illustration as ri  # noqa: E402

_pi_bar_unconstrained = s.pi_bar
PI_MAX = 1.0


def pi_bar_noborrow(x, p):
    return np.minimum(_pi_bar_unconstrained(x, p), PI_MAX)


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def limits(p):
    q = lambda w: w * w * p["sigma"] ** 2 - 2 * w * p["c"] * p["sigma"] * p["sigma_L"] + p["sigma_L"] ** 2
    return dict(nu1=q(1 / p["a1"]), nu3=q(1 / p["a3"]), q1=q(1.0), bound=max(p["sigma_L"] ** 2, q(1 / p["a1"])),
                xbar=(p["a3"] - p["a1"] * p["a2"]) / (p["a3"] - p["a1"]), x_ceiling=1 / (1 - p["a1"]))


def zeta_profile(p, n, cap):
    """zeta along [x_L, y*] under the optimal exposure, with the cap in force."""
    s.pi_bar = cap
    try:
        g = dict(s.GRID, n=n)
        x, v, it, resid = s.solve_howard(p, g)
        th = s.thresholds(x, v, p)
        q = th["q"]
        iL, ist = q["iL"], q["istar"]
        xs = x[iL:ist + 1]
        pi = q["pi"][iL:ist + 1]
        zeta = s.sig2(xs, pi, p) / (xs - 1) ** 2
        capv = cap(xs, p)
        at_cap = np.isclose(pi, capv, rtol=1e-9)
        return dict(x=xs, pi=pi, zeta=zeta, at_cap=at_cap, x_L=th["x_L"], y_star=th["y_star"], y_post=th["y_post"], resid=resid)
    finally:
        s.pi_bar = _pi_bar_unconstrained


def main():
    p0 = dict(s.BASE, lam=1.2, K=0.05)
    L = limits(p0)
    lines = ["# Results: the solve with no borrowing (generated)", "",
             f"Generated by `run_noborrow.py`. Pinned: `solve_qvi.py` sha256 {sha(os.path.join(HERE, 'solve_qvi.py'))}, "
             f"`run_illustration.py` sha256 {sha(os.path.join(HERE, 'run_illustration.py'))}, "
             f"`run_noborrow.py` sha256 {sha(os.path.abspath(__file__))}.", "",
             "Same model, parameters and scheme as `results_solve.md`, with the exposure limited to pi <= 1 (no borrowing; C3).", "",
             f"Limits at these parameters: deficit limit nu_1^2 = {L['nu1']:.4f}, surplus limit nu_3^2 = {L['nu3']:.4f}, "
             f"bound of M12 max(sigma_L^2, nu_1^2) = {L['bound']:.4f}, crossing point xbar = {L['xbar']:.4f}. "
             f"With pi <= 1 the cap is min{{(x-1)/a_1, x}}, whose solvency branch binds only for x <= 1/(1-a_1) = {L['x_ceiling']:.4f}, "
             f"and zeta at pi = 1 is Q(1) = sigma^2 - 2 c sigma sigma_L + sigma_L^2 = {L['q1']:.5f} for every x above that.", ""]

    lines += ["## 1. Buffer variance along the inaction region at (lambda_S, K) = (1.2, 0.05), 1201 nodes", "",
              "| cap | x_L | y_post | y* | zeta at x_L | zeta at y* | max zeta on [x_L, y*] | M12 bound | zeta / nu_3^2 at y* | exposure at the cap | share of the region with pi = cap |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    prof = {}
    for name, cap in (("A2 alone (leveraged)", _pi_bar_unconstrained), ("pi <= 1", pi_bar_noborrow)):
        r = zeta_profile(p0, 1201, cap)
        prof[name] = r
        lines.append(f"| {name} | {r['x_L']:.4f} | {r['y_post']:.4f} | {r['y_star']:.4f} | {r['zeta'][0]:.4f} | {r['zeta'][-1]:.4f} | "
                     f"{r['zeta'].max():.4f} | {L['bound']:.4f} | {r['zeta'][-1] / L['nu3']:.2f} | "
                     f"pi from {r['pi'].min():.2f} to {r['pi'].max():.2f} | {r['at_cap'].mean():.3f} |")
        print(f"profile {name} done", flush=True)
    lines += ["", "zeta on the optimal path, selected nodes (pi <= 1):", "", "| x | pi | zeta | at the cap |", "|---|---|---|---|"]
    r = prof["pi <= 1"]
    for k in np.linspace(0, len(r["x"]) - 1, 9).astype(int):
        lines.append(f"| {r['x'][k]:.4f} | {r['pi'][k]:.3f} | {r['zeta'][k]:.5f} | {'yes' if r['at_cap'][k] else 'no'} |")
    lines.append("")

    s.pi_bar = pi_bar_noborrow
    try:
        lines += ["## 2. The point (lambda_S, K) = (1.2, 0.05), pi <= 1", ""]
        for n in (601, 1201):
            o = s.check_point(ri.POINT, n, 0.02, 0.005)
            lines += [f"### Grid of {n} nodes", "",
                      f"- Discrete QVI residual {o['final_change']:.1e}.",
                      f"- Thresholds: dividend barrier y* = {o['y_star']:.5f}, recapitalisation trigger x_L = {o['x_L']:.5f}, injection target y_post = {o['y_post']:.5f}.",
                      f"- W(y*) = {o['W_y_star']:.5f}, N(y*) = {o['N_y_star']:.4f}, W'(x_L) = {o['W_prime_x_L']:.4f}, N'(x_L) = {o['N_prime_x_L']:.3f}, "
                      f"Psi(x_L) = {o['Psi_x_L']:.5f}, V''(x_L+) = {o['V_second_x_L_plus']:.4f}, V''(y_post) = {o['V_second_y_post']:.4f}, "
                      f"mu'(y*) = {o['mu_prime_y_star']:.4f} against rho_L = {o['rhoL']:.4f}.",
                      f"- Share of the inaction region where the exposure is at the cap: {o['cap_share_inaction']:.3f}.",
                      f"- Envelope identities, max relative error: dV/dlambda_S + W {o['envelope_rel_err_W']:.2e}, dV/dK + N {o['envelope_rel_err_N']:.2e}.",
                      "", "| Response | Formula (M1, M2) | Finite difference |", "|---|---|---|"]
            lines += [f"| {k} | {o['formula'][k]:.5f} | {o['numeric'][k]:.5f} |" for k in o["formula"]]
            lines += [f"| determinant | {o['det_formula']:.5f} | {o['det_numeric']:.5f} |", "",
                      "Hypotheses: " + "; ".join(f"{k} {'holds' if v else 'FAILS'}" for k, v in o["hypotheses"].items()) + ".", ""]
            print(f"point n={n} done", flush=True)

        lines += ["## 3. Regimes of the trigger, pi <= 1, 401 nodes", "",
                  "| lambda_S | K | x_L | y* | regime | W(y*) | W'(x_L) | Psi(x_L) | hypotheses of M1, M2, M4 |", "|---|---|---|---|---|---|---|---|---|"]
        rows = []
        for lam in ri.LAMS:
            for K in ri.KS:
                r = ri.regime(dict(s.BASE, lam=lam, K=K), 401)
                rows.append(r)
                lines.append(f"| {lam} | {K} | {r['x_L']:.4f} | {r['y_star']:.4f} | {r['kind']} | {r['W_y_star']:.4f} | "
                             f"{r['W_prime_x_L']:.3f} | {r['Psi']:.4f} | {'all hold' if r['all_hypotheses'] else 'not all'} |")
                print(f"regime lam={lam} K={K}: {r['kind']}", flush=True)
    finally:
        s.pi_bar = _pi_bar_unconstrained
    counts = {k: sum(1 for r in rows if r["kind"] == k) for k in ("interior", "at the reference", "distress boundary")}
    held = sum(1 for r in rows if r["all_hypotheses"])
    lines += ["", f"Of {len(rows)} points, {counts['interior']} have an interior trigger, {counts['at the reference']} a trigger at the reference "
              f"and {counts['distress boundary']} a trigger at the distress boundary; all hypotheses hold at {held}.", ""]
    open(os.path.join(HERE, "results_noborrow.md"), "w").write("\n".join(lines))
    json.dump({"limits": L, "regimes": rows}, open(os.path.join(HERE, "results_noborrow.json"), "w"), indent=1, default=float)
    print("written results_noborrow.md")


if __name__ == "__main__":
    main()
