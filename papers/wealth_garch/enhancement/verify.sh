#!/usr/bin/env bash
set -u -o pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
cd "$HERE/.."
{
  echo "# Verification of the enhancement paper"
  echo
  echo "Generated by enhancement/verify.sh; do not edit."
  echo
  echo '```'
  python3 enhancement/checks/verify_measurement_map.py
  s1=$?
  python3 enhancement/checks/verify_enhancement.py
  s2=$?
  echo '```'
  echo
  echo "exit codes: measurement map $s1, manuscript $s2"
} > "$HERE/VERIFICATION.md" 2>&1
grep -E "SUMMARY|exit codes" "$HERE/VERIFICATION.md"
grep -q "exit codes: measurement map 0, manuscript 0" "$HERE/VERIFICATION.md"
