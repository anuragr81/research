#!/usr/bin/env bash
set -u -o pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
cd "$HERE/.."
{
  echo "# Verification of the enhancement paper"
  echo
  echo "Generated by enhancement/verify.sh; do not edit."
  echo
  echo '```'
  python3 enhancement/checks/verify_enhancement.py
  status=$?
  echo '```'
} > "$HERE/VERIFICATION.md" 2>&1
grep -E "SUMMARY" "$HERE/VERIFICATION.md"
exit "${status:-1}"
