#!/usr/bin/env bash
# Runs every suite of the Paper A1 skeleton and writes VERIFICATION.md.
# VERIFICATION.md is generated. Never edit it by hand.
set -u -o pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$HERE/VERIFICATION.md"
FAILED=0

{
echo "# Verification status (generated)"
echo
echo "Generated by \`verify.sh\` on $(date -u '+%Y-%m-%d %H:%M UTC'). Do not edit"
echo "by hand. The canonical statement of the results is \`skeleton_ClassMarkers.tex\`; this"
echo "file records only what the checks printed."
} > "$OUT"

suite () {
  local title="$1"; shift
  echo "======================================================================"
  echo " $title"
  echo "======================================================================"
  { echo; echo "## $title"; echo; echo '```'; } >> "$OUT"
  "$@" 2>&1 | tee -a "$OUT" || FAILED=1
  echo '```' >> "$OUT"
  echo
}

suite "Suite 1 - Lean 4 with Mathlib (checks/verify_mathlib.py)" python3 "$HERE/checks/verify_mathlib.py"
suite "Suite 2 - manuscript skeleton (checks/verify_manuscript.py)" python3 "$HERE/checks/verify_manuscript.py"
suite "Suite 3 - doc consistency (checks/verify_docs.py)" python3 "$HERE/checks/verify_docs.py" "$OUT"
suite "Suite 4 - measurement map (checks/verify_measurement_map.py)" python3 "$HERE/checks/verify_measurement_map.py"
suite "Suite 5 - no law of motion (checks/verify_no_law.py)" python3 "$HERE/checks/verify_no_law.py"
suite "Suite 6 - paper records (lit/verify_lit.sh)" bash "$HERE/lit/verify_lit.sh"

if [ "$FAILED" -eq 0 ]; then
  echo "ALL SUITES COMPLETED"
  { echo; echo '## Result'; echo; echo 'All suites completed with no failures.'; } >> "$OUT"
else
  echo "SOME SUITES REPORTED FAILURES"
  { echo; echo '## Result'; echo; echo '**Some suites reported failures.** See the blocks above.'; } >> "$OUT"
fi
exit "$FAILED"
