"""Builds the table of Lean files in Appendix B of MANUSCRIPT.tex from the rows
that cite them, and is imported by verify_docs.py to check the table is
current.

    python checks/lean_files_table.py          print the table
    python checks/lean_files_table.py --write  rewrite it in MANUSCRIPT.tex
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
URL = "https://github.com/anuragr81/research/blob/master/papers/subjective_racism/paper_a/lean/mathlib/"
BEGIN = "% BEGIN LEAN FILES TABLE (generated by checks/lean_files_table.py)"
END = "% END LEAN FILES TABLE"


def brace_args(tex, name, n):
    out = []
    for m in re.finditer(rf"\\{name}(?![A-Za-z])", tex):
        i, args = m.end(), []
        for _ in range(n):
            while i < len(tex) and tex[i].isspace():
                i += 1
            if i >= len(tex) or tex[i] != "{":
                break
            d, j = 0, i
            while j < len(tex):
                if tex[j] == "\\":
                    j += 2
                    continue
                if tex[j] == "{":
                    d += 1
                elif tex[j] == "}":
                    d -= 1
                    if d == 0:
                        break
                j += 1
            args.append(tex[i + 1:j])
            i = j + 1
        if len(args) == n:
            out.append(args)
    return out


def table(tex):
    tex = re.sub(r"(?<!\\)%.*", "", tex)
    cites = {}
    for rid, _, _, lean in brace_args(tex, "mrow", 4):
        for name in [x.strip() for x in lean.split(",") if x.strip()]:
            cites.setdefault(name.split(".")[0], set()).add(rid)
    # an assumption's plain-English reading cites the theorems that check it
    for args in brace_args(tex, "arow", 6):
        for name in re.findall(r"\\lean\{([A-Za-z0-9]+)\.", args[2]):
            cites.setdefault(name, set()).add(args[0])
    lrows = brace_args(tex, "lrow", 6)
    for args in lrows:
        for name in re.findall(r"\\path\{([A-Za-z0-9]+)\.[A-Za-z0-9_']+\}", args[2]):
            cites.setdefault(name, set()).add(args[0])
    # a literature record's Lean file is cited by every L row that cites the record's key,
    # and by the record alone until such a row exists
    for rec in (HERE / "lit").glob("*/LEAN"):
        stem = pathlib.Path(rec.read_text().strip()).stem
        keys = set((rec.parent / "KEYS").read_text().split())
        for args in lrows:
            if args[1].strip() in keys:
                cites.setdefault(stem, set()).add(args[0])
        if stem not in cites:
            cites[stem] = {"record only"}
    # refuted conjectures cite Lean by name in their paragraphs
    for rid, body in re.findall(r"\\paragraph\{(R\d+)\.(.*?)(?=\\paragraph|\\section)", tex, re.S):
        for name in re.findall(r"\\lean\{([A-Za-z0-9]+)\.", body):
            cites.setdefault(name, set()).add(rid)
    mm = (HERE / "MEASUREMENT_MAP.tex").read_text()
    for name in set(re.findall(r"\\lean\{([A-Za-z0-9]+)\.", mm)):
        cites.setdefault(name, set()).add("Measurement map")
    files = sorted(p.stem for p in (HERE / "lean" / "mathlib").glob("*.lean"))

    def key(r):
        m = re.match(r"([A-Z])(\d+)$", r)
        return (0, m.group(1), int(m.group(2))) if m else (1, r, 0)

    lines = [BEGIN,
             r"\begin{longtable}{@{}P{3.4cm}P{8.2cm}P{4.6cm}@{}}",
             r"\caption{Lean files, each a build root, with the rows that cite them.}\label{tab:leanfiles}\\",
             r"\toprule", r"\textbf{Namespace} & \textbf{File} & \textbf{Rows} \\", r"\midrule",
             r"\endfirsthead", r"\toprule",
             r"\textbf{Namespace} & \textbf{File} & \textbf{Rows} \\", r"\midrule", r"\endhead",
             r"\bottomrule", r"\endfoot"]
    for f in files:
        rows = ", ".join(sorted(cites.get(f, set()), key=key)) or "none"
        lines.append(rf"\path{{{f}}} & \href{{{URL}{f}.lean}}{{\path{{lean/mathlib/{f}.lean}}}} & {rows} \\")
    lines += [r"\end{longtable}", END]
    return "\n".join(lines), files, cites


def current(tex):
    m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END), tex, re.S)
    return m.group(0) if m else None


if __name__ == "__main__":
    path = HERE / "MANUSCRIPT.tex"
    tex = path.read_text()
    new, _, _ = table(tex)
    if "--write" in sys.argv:
        old = current(tex)
        if old is None:
            sys.exit("markers not found")
        path.write_text(tex.replace(old, new))
    else:
        print(new)
