# (1) brute-force Bayesian agents
# ---------------------------------------------------------------------------
def sig_lik(p, v, s):
    """Pr(X = s | V = v); s = 1 is H, s = 0 is L (Table 1)."""
    return p if s == v else 1 - p


def bayes_action_probs(p, L1, L0, s):
    """Pr(adopt) for an agent with public likelihoods (L1, L0) and signal s.
    Prior 1/2, C = 1/2: adopt iff E[V] = Pr(V=1) > 1/2, flip a coin at 1/2."""
    a = L1 * sig_lik(p, 1, s)
    b = L0 * sig_lik(p, 0, s)
    if a > b:
        return Fr(1)
    if a < b:
        return Fr(0)
    return Fr(1, 2)


def counting_rule(d, s):
    """The counting characterisation: Pr(adopt) as a function of d and s."""
    if d >= 2:
        return Fr(1)
    if d <= -2:
        return Fr(0)
    if d == 0:
        return Fr(1) if s == 1 else Fr(0)
    if d == 1:
        return Fr(1) if s == 1 else Fr(1, 2)
    # d == -1
    return Fr(1, 2) if s == 1 else Fr(0)


def brute_force(p, N):
    """All action histories of length <= N with their likelihoods under V=1, V=0,
    generated by exact Bayesian agents.  Returns list of dicts by length."""
    layers = [{(): (Fr(1), Fr(1))}]
    rule_ok = True
    for n in range(N):
        nxt = {}
        for h, (L1, L0) in layers[-1].items():
            if L1 == 0 and L0 == 0:
                continue
            d = sum(1 if a else -1 for a in h)
            pa = {}
            for s in (0, 1):
                q = bayes_action_probs(p, L1, L0, s)
                if q != counting_rule(d, s):
                    rule_ok = False
                pa[s] = q
            for a in (1, 0):
                m1 = sum(sig_lik(p, 1, s) * (pa[s] if a else 1 - pa[s]) for s in (0, 1))
                m0 = sum(sig_lik(p, 0, s) * (pa[s] if a else 1 - pa[s]) for s in (0, 1))
                if m1 == 0 and m0 == 0:
                    continue
                nxt[h + (a,)] = (L1 * m1, L0 * m0)
        layers.append(nxt)
    return layers, rule_ok


def classify(h):
    """up / down / none: a cascade has started iff |d| reached 2."""
    d = 0
    for a in h:
        d += 1 if a else -1
        if d >= 2:
            return "up"
        if d <= -2:
            return "down"
    return "none"


def eq1(p, n):
    r = (p - p * p) ** (n // 2)
    return ((1 - r) / 2, r, (1 - r) / 2)


def eq3(p, n):
    r = (p - p * p) ** (n // 2)
    den = 2 * (1 - p + p * p)
    return (p * (p + 1) * (1 - r) / den, r, (p - 2) * (p - 1) * (1 - r) / den)


print("(1)-(2) brute-force Bayesian agents vs counting rule and eqs. (1)-(3)")
for p in (Fr(3, 5), Fr(3, 4), Fr(9, 10)):
    layers, rule_ok = brute_force(p, 10)
    check(f"p={p}: Bayes-optimal rule == counting rule on all histories <= 10", rule_ok)
    # cascade action uninformative: once |d| >= 2 the continuation adds factor 1
    unin = all(
        layers[n + 1].get(h + ((1,) if classify(h) == "up" else (0,)), None) == (L1, L0)
        for n in range(1, 9)
        for h, (L1, L0) in layers[n].items()
        if classify(h) != "none" and (L1, L0) != (0, 0)
    )
    check(f"p={p}: in a cascade the next action leaves both likelihoods unchanged", unin)
    for n in (2, 4, 6, 8, 10):
        tot = {"up": [Fr(0), Fr(0)], "none": [Fr(0), Fr(0)], "down": [Fr(0), Fr(0)]}
        for h, (L1, L0) in layers[n].items():
            c = classify(h)
            tot[c][0] += L1
            tot[c][1] += L0
        unc = tuple((tot[k][0] + tot[k][1]) / 2 for k in ("up", "none", "down"))
        cond = tuple(tot[k][0] for k in ("up", "none", "down"))
        check(f"p={p}, n={n}: eq.(1) unconditional", unc == eq1(p, n))
        check(f"p={p}, n={n}: eqs.(2)/(3) given V=1", cond == eq3(p, n))

# order of signals matters at the population level: same multiset, opposite cascades
def run(signals):
    d = 0
    for s in signals:
        q = counting_rule(d, s)
        assert q in (0, 1), "coin not needed on these paths"
        d += 1 if q == 1 else -1
    return "up" if d >= 2 else "down" if d <= -2 else "none"


check("signals H,H,L,L -> UP cascade; L,L,H,H -> DOWN cascade (same multiset)",
      run([1, 1, 0, 0]) == "up" and run([0, 0, 1, 1]) == "down")

# symbolic: per-agent chain (states -2..2, cascades absorbing) vs closed forms
P = sp.symbols("p", positive=True)


def chain_step(dist, v):
    H = P if v == 1 else 1 - P
    L = 1 - H
    new = {k: 0 for k in (-2, -1, 0, 1, 2)}
    new[2] += dist[2]
    new[-2] += dist[-2]
    new[1] += dist[0] * H
    new[-1] += dist[0] * L
    new[2] += dist[1] * (H + L / 2)
    new[0] += dist[1] * (L / 2)
    new[0] += dist[-1] * (H / 2)
    new[-2] += dist[-1] * (L + H / 2)
    return new


