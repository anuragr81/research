print("\n(6) Result 4 (A5)-(A12)")
A = P * (P + 1) / (2 * (P**2 - P + 1))          # Pr(V=1 | UP started in period 2n)
B = (2 - P) * (1 - P) / (2 * (P**2 - P + 1))    # Pr(V=0 | UP started in period 2n)
